def get_full_prompt(topic: str, duration: int, episode_type: str = None) -> str:
    """에피소드 타입에 맞는 전체 프롬프트 생성"""
    ep_type = episode_type or DEFAULT_EPISODE_TYPE

    # 기본 프롬프트
    full_prompt = PROMPT.format(
        topic=topic,
        duration=duration,
        episode_type=EPISODE_TYPES.get(ep_type, EPISODE_TYPES[DEFAULT_EPISODE_TYPE])["name"]
    )

    # 에피소드 타입별 추가 규칙
    if ep_type in EPISODE_TYPE_RULES:
        full_prompt += "\n\n" + EPISODE_TYPE_RULES[ep_type]

    return full_prompt
